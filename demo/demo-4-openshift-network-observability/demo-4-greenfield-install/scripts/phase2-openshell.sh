#!/usr/bin/env bash
# Phase 2 helper — OpenShell + OpenClaw + private LLM (greenfield).
#
# Usage:
#   ./scripts/phase2-openshell.sh plan          # printable checklist
#   ./scripts/phase2-openshell.sh write-env     # ~/labs/openshell-env.sh from pins
#   ./scripts/phase2-openshell.sh deploy          # automated steps 2–6 (Agent Sandbox → OpenClaw)
#   ./scripts/phase2-openshell.sh check         # pass/fail gates (run after each major step)
#   ./scripts/phase2-openshell.sh harden      # kit patches (after OpenClaw deploy)
#   ./scripts/phase2-openshell.sh providers [profile]  # LLM preset hints (litemaas|vllm|maas-16k|openai)
#   ./scripts/phase2-openshell.sh probe           # full in-pod LLM model probe
#   ./scripts/phase2-openshell.sh ui              # Control UI URL + gateway token
#
# Env: DEMO_KIT_ROOT, OPENCLAW_NS, OPENSHELL_NS, PROBE_*, SKIP_PHASE2_PROBE
set -euo pipefail

GF_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export GF_ROOT
[[ -f "$GF_ROOT/config/env.local" ]] && source "$GF_ROOT/config/env.local"
# shellcheck source=scripts/resolve-demo-kit.sh
source "$GF_ROOT/scripts/resolve-demo-kit.sh"

resolve_kit() {
  resolve_demo_kit
  # shellcheck source=/dev/null
  source "$DEMO_KIT_ROOT/scripts/supply-chain-pins.env"
}

resolve_kit

KUBECTL="$(command -v oc || command -v kubectl)"
OPENCLAW_NS="${OPENCLAW_NS:-openclaw}"
OPENSHELL_NS="${OPENSHELL_NS:-openshell}"
LAB_DIR="${OPENCLAW_LAB_DIR:-$HOME/labs/openshell-on-openshift-lab}"
ENV_FILE="${OPENSHELL_ENV_FILE:-$HOME/labs/openshell-env.sh}"

c_green=$'\033[1;32m'; c_red=$'\033[1;31m'; c_yellow=$'\033[1;33m'; c_blue=$'\033[1;34m'; c_reset=$'\033[0m'
ok()   { printf '  %s✓%s %s\n' "$c_green" "$c_reset" "$*"; }
fail() { printf '  %s✗%s %s\n' "$c_red" "$c_reset" "$*"; }
warn() { printf '  %s!%s %s\n' "$c_yellow" "$c_reset" "$*"; }
step() { printf '\n%s==>%s %s\n' "$c_blue" "$c_reset" "$*"; }

helm_version_ok() {
  command -v helm >/dev/null 2>&1 && helm version --short 2>/dev/null | grep -qE 'v3\.'
}

