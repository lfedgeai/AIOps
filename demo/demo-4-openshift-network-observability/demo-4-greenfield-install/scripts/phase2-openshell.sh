EOF
}

cmd_write_env() {
  step "Writing $ENV_FILE"
  mkdir -p "$(dirname "$ENV_FILE")"
  cat >"$ENV_FILE" <<EOF
# Generated by phase2-openshell.sh — source before OpenShell/OpenClaw work
export OPENCLAW_NAMESPACE=${OPENCLAW_NS}
export OPENSHELL_NAMESPACE=${OPENSHELL_NS}
export OPENSHELL_VERSION=${OPENSHELL_CHART_VERSION}
export AGENT_SANDBOX_RELEASE=${AGENT_SANDBOX_RELEASE}
export AGENT_SANDBOX_MANIFEST="https://github.com/kubernetes-sigs/agent-sandbox/releases/download/\${AGENT_SANDBOX_RELEASE}/manifest.yaml"
