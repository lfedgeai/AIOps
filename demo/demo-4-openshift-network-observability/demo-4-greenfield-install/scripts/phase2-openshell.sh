  printf '\n  source %s\n' "$ENV_FILE"
}

gate() {
  local label="$1"
  shift
  if "$@" >/dev/null 2>&1; then
    ok "$label"
    return 0
  fi
  fail "$label"
  return 1
}

openclaw_pod() {
  "$KUBECTL" -n "$OPENCLAW_NS" get pod -l app.kubernetes.io/name=openclaw \
    --field-selector=status.phase=Running \
    -o jsonpath='{.items[0].metadata.name}' 2>/dev/null
}

cmd_probe() {
  local pod out rc
  PROBE_PROVIDER="${PROBE_PROVIDER:-openai}"
  PROBE_MAX_TOKENS="${PROBE_MAX_TOKENS:-16}"
  PROBE_TIMEOUT="${PROBE_TIMEOUT:-60000}"

  pod="$(openclaw_pod)"
  if [[ -z "$pod" ]]; then
    fail "No Running openclaw pod in namespace ${OPENCLAW_NS}"
    exit 1
  fi

  step "In-pod LLM probe — ${pod} (${OPENCLAW_NS})"
  printf '  provider=%s max_tokens=%s timeout_ms=%s\n' \
    "$PROBE_PROVIDER" "$PROBE_MAX_TOKENS" "$PROBE_TIMEOUT"

  printf '\n--- config validate ---\n'
  "$KUBECTL" -n "$OPENCLAW_NS" exec "$pod" -- sh -lc \
    'set -eu; node /app/openclaw.mjs config validate'

  printf '\n--- openshell gateway ---\n'
  "$KUBECTL" -n "$OPENCLAW_NS" exec "$pod" -- sh -lc \
    'set -eu; openshell status --gateway-endpoint "${OPENSHELL_GATEWAY_URL}"'

  printf '\n--- model probe ---\n'
  set +e
  out="$("$KUBECTL" -n "$OPENCLAW_NS" exec "$pod" -- sh -lc \
    "set -eu
node /app/openclaw.mjs models status --probe \
  --probe-provider ${PROBE_PROVIDER} \
  --probe-max-tokens ${PROBE_MAX_TOKENS} \
  --probe-timeout ${PROBE_TIMEOUT} \
  --json")"
  rc=$?
  set -e
  printf '%s\n' "$out"

  if [[ "$rc" -ne 0 ]]; then
    fail "Model probe command exited ${rc}"
    exit 1
  fi

  if command -v jq >/dev/null 2>&1; then
    if echo "$out" | jq -e '
      (.probe.status // .status // "") == "ok"
      or ([.. | objects | select(has("status")) | .status] | index("ok"))
    ' >/dev/null 2>&1; then
      ok "Model probe status: ok"
      return 0
    fi
  elif echo "$out" | grep -qE '"status"[[:space:]]*:[[:space:]]*"ok"'; then
    ok "Model probe status: ok"
    return 0
  fi

  fail "Model probe did not report ok — check baseUrl, my-llm-key, network policy, contextWindow"
  exit 1
}

cmd_check() {
  local fails=0
  step "Phase 2 readiness — $($KUBECTL whoami 2>/dev/null || echo 'not logged in')"

  if ! helm_version_ok; then
    fail "Helm 3 missing — run: $GF_ROOT/scripts/install-helm3.sh install"
    fails=$((fails + 1))
  else
    ok "Helm 3 installed"
  fi
  gate "Lab checkout @ pin" "$DEMO_KIT_ROOT/scripts/clone-openshell-lab.sh" status || fails=$((fails + 1))
  gate "Agent Sandbox controller" "$KUBECTL" -n agent-sandbox-system get deploy/agent-sandbox-controller || fails=$((fails + 1))
  gate "OpenShell StatefulSet" "$KUBECTL" -n "$OPENSHELL_NS" get statefulset/openshell || fails=$((fails + 1))
  gate "OpenClaw Deployment" "$KUBECTL" -n "$OPENCLAW_NS" get deploy/openclaw || fails=$((fails + 1))
  gate "Secret my-llm-key" "$KUBECTL" -n "$OPENCLAW_NS" get secret/my-llm-key || fails=$((fails + 1))
  gate "Secret openclaw-gateway-token" "$KUBECTL" -n "$OPENCLAW_NS" get secret/openclaw-gateway-token || fails=$((fails + 1))
  gate "OpenClaw Route" "$KUBECTL" -n "$OPENCLAW_NS" get route/openclaw || fails=$((fails + 1))

  if [[ -f "${LAB_DIR}/manifests/openclaw/config.yaml" ]]; then
    if grep -q 'api.openai.com' "${LAB_DIR}/manifests/openclaw/config.yaml" 2>/dev/null \
      && ! grep -qE 'litemaas|maas-|vllm|\.svc' "${LAB_DIR}/manifests/openclaw/config.yaml" 2>/dev/null; then
      warn "config.yaml may still point at public OpenAI — confirm baseUrl + network policy"
    else
      ok "config.yaml edited (non-default LLM host)"
    fi
  else
    fail "lab config.yaml missing at ${LAB_DIR}/manifests/openclaw/config.yaml"
    fails=$((fails + 1))
  fi

  if POD="$("$KUBECTL" -n "$OPENCLAW_NS" get pod -l app.kubernetes.io/name=openclaw \
    --field-selector=status.phase=Running -o jsonpath='{.items[0].metadata.name}' 2>/dev/null)" \
    && [[ -n "$POD" ]]; then
    if "$KUBECTL" -n "$OPENCLAW_NS" exec "$POD" -- sh -lc \
      'node /app/openclaw.mjs config validate' >/dev/null 2>&1; then
      ok "OpenClaw config validate (in-pod)"
    else
      fail "OpenClaw config validate (in-pod)"
      fails=$((fails + 1))
    fi
  else
    warn "OpenClaw pod not Running — skip in-pod validate"
  fi

  printf '\n'
  if [[ "$fails" -gt 0 ]]; then
    warn "$fails check(s) failed — see $GF_ROOT/docs/PHASE-2-OPENSHELL.md#troubleshooting"
    return 1
  fi
  ok "Phase 2 checks passed"
  printf '  LLM probe: ./scripts/phase2-openshell.sh probe\n'
  printf '  Control UI: %s/scripts/netobserv-e2e-openclaw-test.sh ui-hints\n' "$DEMO_KIT_ROOT"
}

